-- Создание таблицы Products
CREATE TABLE Products (
    ProductID INT PRIMARY KEY,        -- Идентификатор товара
    ProductName VARCHAR(100),         -- Название товара
    Category VARCHAR(50),             -- Категория товара (например, электроника, бытовая техника)
    Price DECIMAL(10, 2),             -- Цена товара
    Stock INT                        -- Количество товара в наличии
);

