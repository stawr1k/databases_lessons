-- Создание таблицы Orders
CREATE TABLE Orders (
    OrderID INT PRIMARY KEY,              -- Идентификатор заказа
    CustomerName VARCHAR(100),            -- Имя покупателя
    ProductID INT,                        -- Идентификатор товара (ссылается на ProductID из таблицы Products)
    Quantity INT,                         -- Количество заказанных товаров
    OrderDate DATE,                       -- Дата заказа
    FOREIGN KEY (ProductID) REFERENCES Products(ProductID) -- Внешний ключ на ProductID
);

