-- 1. Таблица Directors (Режиссеры)
-- Хранит информацию о режиссерах
CREATE TABLE Directors (
    director_id SERIAL PRIMARY KEY,      -- Уникальный идентификатор режиссера
    director_name VARCHAR(100) NOT NULL,  -- Имя режиссера
    birthdate DATE,                       -- Дата рождения
    nationality VARCHAR(100)             -- Национальность
);

-- 2. Таблица Users (Пользователи)
-- Хранит информацию о пользователях сайта
CREATE TABLE Users (
    user_id SERIAL PRIMARY KEY,         -- Уникальный идентификатор пользователя
    username VARCHAR(50) UNIQUE NOT NULL, -- Имя пользователя (уникальное)
    email VARCHAR(100) UNIQUE NOT NULL,  -- Электронная почта (уникальная)
    password_hash VARCHAR(255) NOT NULL, -- Хэш пароля
    registration_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP, -- Дата регистрации
    is_admin BOOLEAN DEFAULT FALSE      -- Признак администратора (по умолчанию FALSE)
);

-- 3. Таблица Movies (Фильмы)
-- Хранит информацию о фильмах
CREATE TABLE Movies (
    movie_id SERIAL PRIMARY KEY,         -- Уникальный идентификатор фильма
    title VARCHAR(255) NOT NULL,         -- Название фильма
    description TEXT,                    -- Описание фильма
    release_year INT,                    -- Год выпуска
    duration INT,                        -- Продолжительность фильма (в минутах)
    country VARCHAR(100),                -- Страна производства
    director_id INT REFERENCES Directors(director_id), -- Связь с таблицей Directors
    related_movie_id INT REFERENCES Movies(movie_id) -- Связь с другим фильмом (self-join)
);

-- 4. Таблица Genres (Жанры)
-- Хранит список всех возможных жанров
CREATE TABLE Genres (
    genre_id SERIAL PRIMARY KEY,         -- Уникальный идентификатор жанра
    genre_name VARCHAR(100) UNIQUE NOT NULL -- Название жанра (уникальное)
);

-- 5. Таблица MovieGenres (Жанры фильмов)
-- Связь многие-ко-многим между фильмами и жанрами
CREATE TABLE MovieGenres (
    movie_id INT NOT NULL,               -- Идентификатор фильма
    genre_id INT NOT NULL,               -- Идентификатор жанра
    PRIMARY KEY (movie_id, genre_id),    -- Первичный ключ по комбинации (movie_id, genre_id)
    FOREIGN KEY (movie_id) REFERENCES Movies(movie_id) ON DELETE CASCADE, -- Внешний ключ на таблицу Movies
    FOREIGN KEY (genre_id) REFERENCES Genres(genre_id) ON DELETE CASCADE -- Внешний ключ на таблицу Genres
);

-- 6. Таблица Ratings (Рейтинги)
-- Хранит информацию о рейтингах, которые пользователи присваивают фильмам
CREATE TABLE Ratings (
    rating_id SERIAL PRIMARY KEY,        -- Уникальный идентификатор рейтинга
    user_id INT NOT NULL,                -- Идентификатор пользователя
    movie_id INT NOT NULL,               -- Идентификатор фильма
    rating INT,                          -- Рейтинг от 1 до 10
    rating_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP, -- Дата установки рейтинга
    UNIQUE(user_id, movie_id),           -- Один пользователь может оценить фильм только один раз
    FOREIGN KEY (user_id) REFERENCES Users(user_id) ON DELETE CASCADE, -- Внешний ключ на таблицу Users
    FOREIGN KEY (movie_id) REFERENCES Movies(movie_id) ON DELETE CASCADE -- Внешний ключ на таблицу Movies
);

-- 7. Таблица Reviews (Рецензии)
-- Хранит рецензии пользователей на фильмы
CREATE TABLE Reviews (
    review_id SERIAL PRIMARY KEY,        -- Уникальный идентификатор рецензии
    user_id INT NOT NULL,                -- Идентификатор пользователя
    movie_id INT NOT NULL,               -- Идентификатор фильма
    review_text TEXT NOT NULL,           -- Текст рецензии
    review_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP, -- Дата добавления рецензии
    UNIQUE(user_id, movie_id),           -- Один пользователь может оставить только одну рецензию
    FOREIGN KEY (user_id) REFERENCES Users(user_id) ON DELETE CASCADE, -- Внешний ключ на таблицу Users
    FOREIGN KEY (movie_id) REFERENCES Movies(movie_id) ON DELETE CASCADE -- Внешний ключ на таблицу Movies
);

-- 8. Таблица Favorites (Избранное)
-- Хранит информацию о фильмах, добавленных пользователями в избранное
CREATE TABLE Favorites (
    favorite_id SERIAL PRIMARY KEY,      -- Уникальный идентификатор избранного
    user_id INT NOT NULL,                -- Идентификатор пользователя
    movie_id INT NOT NULL,               -- Идентификатор фильма
    added_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP, -- Дата добавления в избранное
    UNIQUE(user_id, movie_id),           -- Один фильм может быть добавлен в избранное только один раз
    FOREIGN KEY (user_id) REFERENCES Users(user_id) ON DELETE CASCADE, -- Внешний ключ на таблицу Users
    FOREIGN KEY (movie_id) REFERENCES Movies(movie_id) ON DELETE CASCADE -- Внешний ключ на таблицу Movies
);

-- 9. Таблица Actors (Актеры)
-- Хранит информацию об актерах
CREATE TABLE Actors (
    actor_id SERIAL PRIMARY KEY,         -- Уникальный идентификатор актера
    actor_name VARCHAR(100) NOT NULL,     -- Имя актера
    birthdate DATE,                       -- Дата рождения
    nationality VARCHAR(100)             -- Национальность
);

-- 10. Таблица MovieActors (Актеры в фильмах)
-- Связь многие-ко-многим между фильмами и актерами
CREATE TABLE MovieActors (
    movie_id INT NOT NULL,               -- Идентификатор фильма
    actor_id INT NOT NULL,               -- Идентификатор актера
    role_name VARCHAR(100),              -- Имя персонажа в фильме
    PRIMARY KEY (movie_id, actor_id),    -- Первичный ключ по комбинации (movie_id, actor_id)
    FOREIGN KEY (movie_id) REFERENCES Movies(movie_id) ON DELETE CASCADE, -- Внешний ключ на таблицу Movies
    FOREIGN KEY (actor_id) REFERENCES Actors(actor_id) ON DELETE CASCADE -- Внешний ключ на таблицу Actors
);

-- 11. Таблица MovieDirectors (Режиссеры в фильмах)
-- Связь многие-ко-многим между фильмами и режиссерами
CREATE TABLE MovieDirectors (
    movie_id INT NOT NULL,               -- Идентификатор фильма
    director_id INT NOT NULL,            -- Идентификатор режиссера
    PRIMARY KEY (movie_id, director_id), -- Первичный ключ по комбинации (movie_id, director_id)
    FOREIGN KEY (movie_id) REFERENCES Movies(movie_id) ON DELETE CASCADE, -- Внешний ключ на таблицу Movies
    FOREIGN KEY (director_id) REFERENCES Directors(director_id) ON DELETE CASCADE -- Внешний ключ на таблицу Directors
);


